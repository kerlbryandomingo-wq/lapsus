import android.app.DownloadManager
import android.content.ActivityNotFoundException
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import android.database.Cursor
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.webkit.CookieManager
import android.webkit.URLUtil
import androidx.core.content.ContextCompat
import com.krlbryn.sophia.core.FileNames
import com.krlbryn.sophia.core.UrlPolicy
import com.krlbryn.sophia.data.db.DownloadDao
import com.krlbryn.sophia.data.db.DownloadRecord
import com.krlbryn.sophia.data.settings.DownloadLocation
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.flow.flowOn
import kotlinx.coroutines.flow.first
import javax.inject.Inject
import javax.inject.Singleton

enum class DownloadState { QUEUED, RUNNING, WAITING, COMPLETE, FAILED, CANCELLED, MISSING }

/** A download as shown in the Downloads screen: the stored record plus live status from DownloadManager. */
data class DownloadItem(
    val record: DownloadRecord,
    val state: DownloadState,
    val downloadedBytes: Long,
    val totalBytes: Long,
    /** Human explanation for WAITING and FAILED states. */
    val reason: String?,
) {
    val progress: Float? get() = if (totalBytes > 0) (downloadedBytes.toFloat() / totalBytes).coerceIn(0f, 1f) else null
    val active: Boolean get() = state == DownloadState.QUEUED || state == DownloadState.RUNNING || state == DownloadState.WAITING
}

sealed interface EnqueueResult {
    data class Started(val fileName: String, val location: DownloadLocation) : EnqueueResult
    data class Rejected(val message: String) : EnqueueResult
}

/**
 * Downloads go through Android's DownloadManager, which survives Sophia being closed, shows its own
 * notification, retries on network loss, and writes through scoped storage. Sophia keeps a record of
 * each download in Room so the list survives and can show file details.
 */
@Singleton
class DownloadsRepository @Inject constructor(
    @ApplicationContext private val context: Context,
    private val dao: DownloadDao,
) {
    private val dm: DownloadManager get() = context.getSystemService(DownloadManager::class.java)

    fun needsStoragePermission(): Boolean =
        Build.VERSION.SDK_INT < Build.VERSION_CODES.Q &&
            ContextCompat.checkSelfPermission(context, Manifest.permission.WRITE_EXTERNAL_STORAGE) != PackageManager.PERMISSION_GRANTED

    suspend fun enqueue(
        url: String,
        userAgent: String?,
        contentDisposition: String?,
        mimeType: String?,
        preferred: DownloadLocation,
    ): EnqueueResult {
        val scheme = UrlPolicy.schemeOf(url)
        if (scheme != "https" && scheme != "http") {
            return EnqueueResult.Rejected("This file is generated by the page and can't be downloaded by Sophia.")
        }
        if (!UrlPolicy.isSafeExternalUrl(url)) return EnqueueResult.Rejected("This download link isn't valid.")

        val guessed = URLUtil.guessFileName(url, contentDisposition, mimeType)
        val fileName = FileNames.sanitize(guessed)
        val location = if (preferred == DownloadLocation.PUBLIC_DOWNLOADS && needsStoragePermission()) {
            DownloadLocation.APP_STORAGE
        } else {
            preferred
        }
        val request = DownloadManager.Request(Uri.parse(url)).apply {
            setTitle(fileName)
            setDescription(UrlPolicy.hostOf(url))
            mimeType?.takeIf { it.isNotBlank() }?.let { setMimeType(it) }
            userAgent?.let { addRequestHeader("User-Agent", it) }
            // The portal serves files only to signed-in sessions; pass the WebView's cookies for this URL.
            CookieManager.getInstance().getCookie(url)?.let { addRequestHeader("Cookie", it) }
            setNotificationVisibility(DownloadManager.Request.VISIBILITY_VISIBLE_NOTIFY_COMPLETED)
            when (location) {
                DownloadLocation.PUBLIC_DOWNLOADS ->
                    setDestinationInExternalPublicDir(Environment.DIRECTORY_DOWNLOADS, "Sophia/$fileName")
                DownloadLocation.APP_STORAGE ->
                    setDestinationInExternalFilesDir(context, Environment.DIRECTORY_DOWNLOADS, fileName)
            }
        }
        val systemId = try {
            dm.enqueue(request)
        } catch (e: IllegalArgumentException) {
            return EnqueueResult.Rejected("Android could not start this download.")
        } catch (e: IllegalStateException) {
            return EnqueueResult.Rejected("The download folder isn't available right now.")
        }
        dao.insert(DownloadRecord(systemId = systemId, url = url, fileName = fileName, mimeType = mimeType, location = location.name))
        return EnqueueResult.Started(fileName, location)
    }

    /** Live list. Polls DownloadManager while collected: quickly while something is downloading, slowly otherwise. */
    fun observe(): Flow<List<DownloadItem>> = flow {
        while (true) {
            val records = dao.all().first()
            val items = query(records)
            emit(items)
            delay(if (items.any { it.active }) 700L else 3000L)
        }
    }.flowOn(Dispatchers.IO)

    private fun query(records: List<DownloadRecord>): List<DownloadItem> {
        if (records.isEmpty()) return emptyList()
        val live = mutableMapOf<Long, DownloadItem>()
        val ids = records.filterNot { it.cancelled }.map { it.systemId }.toLongArray()
        if (ids.isNotEmpty()) {
            dm.query(DownloadManager.Query().setFilterById(*ids))?.use { c ->
                while (c.moveToNext()) {
                    val id = c.long(DownloadManager.COLUMN_ID)
                    val record = records.first { it.systemId == id }
                    live[id] = toItem(record, c)
                }
            }
        }
        return records.map { r ->
            live[r.systemId] ?: DownloadItem(
                record = r,
                state = if (r.cancelled) DownloadState.CANCELLED else DownloadState.MISSING,
                downloadedBytes = 0,
                totalBytes = -1,
                reason = if (r.cancelled) null else "The file was removed outside Sophia.",
            )
        }
    }

    private fun toItem(record: DownloadRecord, c: Cursor): DownloadItem {
        val status = c.int(DownloadManager.COLUMN_STATUS)
        val reasonCode = c.int(DownloadManager.COLUMN_REASON)
        val state = when (status) {
            DownloadManager.STATUS_PENDING -> DownloadState.QUEUED
            DownloadManager.STATUS_RUNNING -> DownloadState.RUNNING
            DownloadManager.STATUS_PAUSED -> DownloadState.WAITING
            DownloadManager.STATUS_SUCCESSFUL -> DownloadState.COMPLETE
            else -> DownloadState.FAILED
        }
        val reason = when (state) {
            DownloadState.WAITING -> when (reasonCode) {
                DownloadManager.PAUSED_WAITING_FOR_NETWORK -> "Waiting for a network connection"
                DownloadManager.PAUSED_QUEUED_FOR_WIFI -> "Waiting for Wi-Fi"
                DownloadManager.PAUSED_WAITING_TO_RETRY -> "Connection lost, retrying soon"
                else -> "Paused by Android"
            }
            DownloadState.FAILED -> when (reasonCode) {
                DownloadManager.ERROR_INSUFFICIENT_SPACE -> "Not enough storage space"
                DownloadManager.ERROR_DEVICE_NOT_FOUND -> "Storage isn't available"
                DownloadManager.ERROR_FILE_ALREADY_EXISTS -> "A file with this name already exists"
                DownloadManager.ERROR_TOO_MANY_REDIRECTS -> "The site redirected too many times"
                DownloadManager.ERROR_HTTP_DATA_ERROR, DownloadManager.ERROR_CANNOT_RESUME -> "The connection was interrupted"
                in 400..599 -> "The site refused the download (HTTP $reasonCode). You may need to sign in again."
                else -> "The download failed"
            }
            else -> null
        }
        return DownloadItem(
            record = record,
            state = state,
            downloadedBytes = c.long(DownloadManager.COLUMN_BYTES_DOWNLOADED_SO_FAR),
            totalBytes = c.long(DownloadManager.COLUMN_TOTAL_SIZE_BYTES),
            reason = reason,
        )
    }

    /** Stops a download and removes its partial file. */
    suspend fun cancel(item: DownloadItem) {
        dm.remove(item.record.systemId)
        dao.update(item.record.copy(cancelled = true))
    }

    /** Starts the same download again (with fresh cookies) and replaces the old entry. */
    suspend fun retry(item: DownloadItem, userAgent: String?, preferred: DownloadLocation): EnqueueResult {
        if (!item.record.cancelled) dm.remove(item.record.systemId)
        dao.delete(item.record.id)
        return enqueue(item.record.url, userAgent, null, item.record.mimeType, preferred)
    }

    /** Removes the entry from the list; with [deleteFile] also deletes the downloaded file. */
    suspend fun remove(item: DownloadItem, deleteFile: Boolean) {
        if (deleteFile && !item.record.cancelled) dm.remove(item.record.systemId)
        dao.delete(item.record.id)
    }

    /** Opens a finished file with another app through a content:// URI and a temporary read grant. */
    fun open(item: DownloadItem): Boolean {
        val uri = dm.getUriForDownloadedFile(item.record.systemId) ?: return false
        val type = item.record.mimeType?.takeIf { it.isNotBlank() } ?: dm.getMimeTypeForDownloadedFile(item.record.systemId)
        val intent = Intent(Intent.ACTION_VIEW).apply {
            setDataAndType(uri, type ?: "*/*")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        return try {
            context.startActivity(Intent.createChooser(intent, "Open with").addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
            true
        } catch (e: ActivityNotFoundException) {
            false
        }
    }

    private fun Cursor.long(column: String): Long = getLong(getColumnIndexOrThrow(column))
    private fun Cursor.int(column: String): Int = getInt(getColumnIndexOrThrow(column))
}
