/**
 * Release signing comes from environment variables (CI) or an untracked keystore.properties file.
 * Nothing secret is ever committed. Without them, release builds are produced unsigned.
 * See android/docs/RELEASING.md.
 */
val signingProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: signingProps.getProperty(prop)?.takeIf { it.isNotBlank() }

