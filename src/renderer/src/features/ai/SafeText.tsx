import type { ReactNode } from 'react';

/**
 * Renders AI text as React nodes. Supports paragraphs, "- " bullet lines, **bold** and `code`.
 * No HTML is ever interpreted, so model output cannot inject markup, links or scripts.
 */
export function SafeText({ text }: { text: string }) {
  const blocks = text.replace(/\r\n?/g, '\n').split(/\n{2,}/);
  return (
    <>
      {blocks.map((block, i) => {
        const lines = block.split('\n').filter((l) => l.trim());
        if (lines.length > 0 && lines.every((l) => /^\s*[-*•]\s+/.test(l))) {
          return (
            <ul key={i} className="safe-list">
              {lines.map((l, j) => (
                <li key={j}>{inline(l.replace(/^\s*[-*•]\s+/, ''))}</li>
              ))}
            </ul>
          );
        }
        return (
          <p key={i} className="safe-p">
            {lines.map((l, j) => (
              <span key={j}>
                {j > 0 && <br />}
                {inline(l)}
              </span>
            ))}
          </p>
        );
      })}
    </>
  );
}

function inline(text: string): ReactNode[] {
  const out: ReactNode[] = [];
  const re = /(\*\*[^*]+\*\*|`[^`]+`)/g;
  let last = 0;
  let m: RegExpExecArray | null;
  let k = 0;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push(text.slice(last, m.index));
    const token = m[0];
    if (token.startsWith('**')) out.push(<strong key={k++}>{token.slice(2, -2)}</strong>);
    else out.push(<code key={k++}>{token.slice(1, -1)}</code>);
    last = m.index + token.length;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}

/** Plain-text version of an answer for the clipboard. */
export function answerToText(a: {
  questionSummary: string;
  leadingOption: string | null;
  explanation: string;
  evidence: string[];
  inferences: string[];
  missingInformation: string[];
  confidence: string;
  confidenceReason: string;
  warning: string | null;
}): string {
  const parts = [
    `Question: ${a.questionSummary}`,
    a.leadingOption ? `Leading option (not verified): ${a.leadingOption}` : 'Leading option: none',
    '',
    a.explanation,
  ];
  if (a.evidence.length) parts.push('', 'Supported by the material:', ...a.evidence.map((e) => `- ${e}`));
  if (a.inferences.length) parts.push('', 'Reasoning (inference):', ...a.inferences.map((e) => `- ${e}`));
  if (a.missingInformation.length) parts.push('', 'Missing information:', ...a.missingInformation.map((e) => `- ${e}`));
  parts.push('', `Confidence: ${a.confidence}. ${a.confidenceReason}`);
  if (a.warning) parts.push('', `Warning: ${a.warning}`);
  parts.push('', 'AI-generated by Lapsus Study Assistant. Check it against your course material.');
  return parts.join('\n');
}
